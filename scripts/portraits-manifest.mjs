/**
 * Portraits are served as `<id>.webp?v=<hash>`, where the hash is the first
 * eight hex digits of the SHA-256 of the file's bytes.
 *
 * Caches key on the whole URL, query string included. The stamp is what lets
 * the folder be served `immutable`. A replaced portrait arrives under a query
 * nobody has cached, instead of waiting out a year of someone's cache.
 *
 * The stamp goes in the query rather than the file name so the folder stays
 * readable. `luffy.webp` is still `luffy.webp` on disk.
 *
 * The manifest is whatever is on disk. Portraits come from two sources, so
 * neither fetch script can generate it from its own results without dropping
 * the other's work.
 */
import { createHash } from 'node:crypto';
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const OUT_DIR = 'public/portraits';
const MANIFEST = 'src/data/portraits.ts';
const STAMP_LENGTH = 8;

export function stampOf(buffer) {
  return createHash('sha256')
    .update(buffer)
    .digest('hex')
    .slice(0, STAMP_LENGTH);
}

export function writePortrait(id, buffer) {
  writeFileSync(join(OUT_DIR, `${id}.webp`), buffer);
  return stampOf(buffer);
}

/** The stamp for this character's file, or null where there is none. */
export function stampFor(id) {
  try {
    return stampOf(readFileSync(join(OUT_DIR, `${id}.webp`)));
  } catch {
    return null;
  }
}

export function writeManifest() {
  const stamps = readdirSync(OUT_DIR)
    .filter(name => name.endsWith('.webp'))
    .map(name => [
      name.slice(0, -'.webp'.length),
      stampOf(readFileSync(join(OUT_DIR, name))),
    ])
    .sort(([a], [b]) => a.localeCompare(b));

  writeFileSync(
    MANIFEST,
    [
      '// Generated by scripts/fetch-portraits.mjs. Do not edit by hand.',
      '',
      '/** Character id to the stamp public/portraits/<id>.webp is served under. */',
      'export const PORTRAIT_STAMPS: ReadonlyMap<string, string> = new Map([',
      ...stamps.map(([id, stamp]) => `  ['${id}', '${stamp}'],`),
      ']);',
      '',
    ].join('\n'),
  );

  return stamps.length;
}
