/**
 * The portrait manifest is whatever is on disk.
 *
 * Portraits come from two sources now, so neither fetch script can generate
 * the manifest from its own results without dropping the other's files.
 */
import { readdirSync, writeFileSync } from 'node:fs';

const OUT_DIR = 'public/portraits';
const MANIFEST = 'src/data/portraits.ts';

export function writeManifest() {
  const ids = readdirSync(OUT_DIR)
    .filter(name => name.endsWith('.webp'))
    .map(name => name.slice(0, -'.webp'.length))
    .sort((a, b) => a.localeCompare(b));

  writeFileSync(
    MANIFEST,
    [
      '// Generated by scripts/fetch-portraits.mjs. Do not edit by hand.',
      '',
      '/** Character ids with a file at public/portraits/<id>.webp. */',
      'export const PORTRAIT_IDS: ReadonlySet<string> = new Set([',
      ...ids.map(id => `  '${id}',`),
      ']);',
      '',
    ].join('\n'),
  );

  return ids.length;
}
